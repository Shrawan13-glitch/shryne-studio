import type { StudioConfig } from '@/types';
import { GithubClient, NotFoundError } from './client';
import { WORKFLOW_PATH, WORKFLOW_YAML } from './workflow';

export interface RepoInfo {
  full_name: string;
  default_branch: string;
  private: boolean;
}

export async function getRepo(client: GithubClient, owner: string, name: string): Promise<RepoInfo | null> {
  try {
    return await client.request<RepoInfo>(`/repos/${owner}/${name}`);
  } catch (error) {
    if (error instanceof NotFoundError) return null;
    throw error;
  }
}

export async function createPublicRepo(client: GithubClient, name: string): Promise<RepoInfo> {
  return client.request<RepoInfo>('/user/repos', {
    method: 'POST',
    body: JSON.stringify({
      name,
      private: false,
      auto_init: true,
      description: 'Audio generated by Shryne Studio — managed by the ShryneTTS GitHub Action.',
    }),
  });
}

function toBase64(text: string): string {
  // btoa is available in the RN JS runtime and in Node 18+.
  const bytes = new TextEncoder().encode(text);
  let binary = '';
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary);
}

export async function putFile(
  client: GithubClient,
  repo: string,
  path: string,
  content: string,
  branch: string,
  message: string,
  sha?: string,
): Promise<void> {
  await client.request(`/repos/${repo}/contents/${path}`, {
    method: 'PUT',
    body: JSON.stringify({ message, content: toBase64(content), branch, ...(sha ? { sha } : {}) }),
  });
}

export async function getFileSha(client: GithubClient, repo: string, path: string, branch: string): Promise<string | undefined> {
  try {
    const response = await client.request<{ sha: string }>(
      `/repos/${repo}/contents/${path}?ref=${encodeURIComponent(branch)}`,
    );
    return response.sha;
  } catch (error) {
    if (error instanceof NotFoundError) return undefined;
    throw error;
  }
}

export interface ProvisionResult {
  config: StudioConfig;
  createdRepo: boolean;
  installedWorkflow: boolean;
}

/** Idempotently prepare everything the app needs: public repo + default branch + workflow file. */
export async function provisionStudio(client: GithubClient, login: string, token: string, tokenKind: 'classic' | 'fine-grained'): Promise<ProvisionResult> {
  const name = 'shryne-studio-audio';
  const fullName = `${login}/${name}`;
  let repo = await getRepo(client, login, name);
  let createdRepo = false;
  if (!repo) {
    repo = await createPublicRepo(client, name);
    createdRepo = true;
  }

  const branch = repo.default_branch || 'main';
  const existingSha = await getFileSha(client, fullName, WORKFLOW_PATH, branch);
  // Always rewrite the workflow so app updates propagate, keeping the file pinned to @v1.
  await putFile(client, fullName, WORKFLOW_PATH, WORKFLOW_YAML, branch, 'chore: install Shryne Studio TTS workflow', existingSha);

  return {
    config: {
      token,
      tokenKind,
      login,
      owner: login,
      repo: fullName,
      defaultBranch: branch,
      workflowPath: WORKFLOW_PATH,
      connectedAt: Date.now(),
    },
    createdRepo,
    installedWorkflow: true,
  };
}
