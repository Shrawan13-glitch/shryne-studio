private const val REPO_NAME = "shryne-studio-audio"
private const val WORKFLOW_PATH = ".github/workflows/tts-studio.yml"

class StudioViewModel(app: Application) : AndroidViewModel(app) {
    private val tokens = TokenStore(app)
    private val local = LocalStore(app)
    private val files = FileStore(app)
    private val gson = Gson()

    val token = mutableStateOf(tokens.token ?: "")
    val login = mutableStateOf(tokens.login ?: "")
    val repo = mutableStateOf(tokens.repo ?: "")
    val connected = mutableStateOf(tokens.token != null)
    val busy = mutableStateOf(false)
    val status = mutableStateOf<String?>(null)
    val error = mutableStateOf<String?>(null)

    val scripts = mutableStateListOf<Script>()
    val runs = mutableStateListOf<Run>()
    val assets = mutableStateListOf<Asset>()

    init {
        if (connected.value) loadLocal()
    }

    private fun client(): GithubClient = GithubClient(tokens.token ?: error("Not connected"))

    private fun loadLocal() {
        scripts.clear(); scripts.addAll(local.scripts())
        runs.clear(); runs.addAll(local.runs())
        assets.clear(); assets.addAll(local.assets())
    }

    private fun persistScripts() = local.saveScripts(scripts)
    private fun persistRuns() = local.saveRuns(runs)
    private fun persistAssets() = local.saveAssets(assets)

    fun clearError() { error.value = null }

    fun connect(value: String) {
        busy.value = true
        status.value = "Validating token"
        error.value = null
        viewModelScope.launch(Dispatchers.IO) {
            try {
                val api = GithubClient(value.trim())
                val user = JSONObject(api.get("/user"))
                val who = user.getString("login")
                status.value = "Preparing public repo"
                val repoPath = "/repos/$who/$REPO_NAME"
                var defaultBranch = "main"
                try {
                    val info = JSONObject(api.get(repoPath))
                    defaultBranch = info.optString("default_branch", "main")
                } catch (e: GithubException) {
                    if (e.status != 404) throw e
                    val created = JSONObject(api.post("/user/repos", JSONObject().apply {
                        put("name", REPO_NAME)
                        put("private", false)
                        put("auto_init", true)
                        put("description", "Audio generated by Shryne Studio")
                    }.toString()))
                    defaultBranch = created.optString("default_branch", "main")
                }
                status.value = "Installing workflow"
                val yaml = getApplication<Application>().resources.openRawResource(R.raw.tts_studio)
                    .bufferedReader().use { it.readText() }
                var sha: String? = null
                try {
                    val existing = JSONObject(api.get("/repos/$who/$REPO_NAME/contents/$WORKFLOW_PATH?ref=$defaultBranch"))
                    sha = existing.optString("sha")
                } catch (e: GithubException) {
                    if (e.status != 404) throw e
                }
                val body = JSONObject().apply {
                    put("message", "chore: install Shryne Studio workflow")
                    put("content", Base64.encodeToString(yaml.toByteArray(), Base64.DEFAULT))
                    put("branch", defaultBranch)
                    if (sha != null) put("sha", sha)
                }.toString()
                api.put("/repos/$who/$REPO_NAME/contents/$WORKFLOW_PATH", body)

                tokens.token = value.trim()
                tokens.login = who
                tokens.repo = "$who/$REPO_NAME"
                tokens.branch = defaultBranch
                withContext(Dispatchers.Main) {
                    token.value = value.trim()
                    login.value = who
                    repo.value = "$who/$REPO_NAME"
                    connected.value = true
                    loadLocal()
                }
            } catch (e: Exception) {
                withContext(Dispatchers.Main) { error.value = e.message ?: "Could not connect" }
            } finally {
                withContext(Dispatchers.Main) { busy.value = false; status.value = null }
            }
        }
    }

    fun disconnect() {
        tokens.clear()
        connected.value = false
        scripts.clear(); runs.clear(); assets.clear()
    }

    fun newScript(title: String = "Untitled script"): Script {
        val script = Script(title = title, blocks = mutableListOf(
            Block(text = "Hello from Shryne Studio.", voice = "af_sky", speed = 1.0),
        ))
        scripts.add(0, script)
        persistScripts()
        return script
    }

    fun saveScript(script: Script) {
        val index = scripts.indexOfFirst { it.id == script.id }
        if (index >= 0) scripts[index] = script.copy(updatedAt = System.currentTimeMillis()) else scripts.add(script)
        persistScripts()
    }

    fun deleteScript(id: String) {
        scripts.removeAll { it.id == id }
        persistScripts()
    }

    fun generate(script: Script, shards: Int, strategy: String, retention: Int, cleanup: Boolean) {
        val compiled = Compiler.compile(script.blocks, script)
        if (compiled.items.isEmpty()) { error.value = "Add at least one spoken line."; return }
        busy.value = true
        error.value = null
        status.value = "Committing script"
        viewModelScope.launch(Dispatchers.IO) {
            try {
                val api = client()
                val branch = tokens.branch ?: "main"
                val path = "scripts/${compiled.batchId}.json"
                var sha: String? = null
                try {
                    val existing = JSONObject(api.get("/repos/${repo.value}/contents/$path?ref=$branch"))
                    sha = existing.optString("sha")
                } catch (e: GithubException) {
                    if (e.status != 404) throw e
                }
                val commit = JSONObject().apply {
                    put("message", "tts(batch): ${compiled.batchId}")
                    put("content", Base64.encodeToString(compiled.toItemsJson().toByteArray(), Base64.DEFAULT))
                    put("branch", branch)
                    if (sha != null) put("sha", sha)
                }.toString()
                api.put("/repos/${repo.value}/contents/$path", commit)

                status.value = "Dispatching workflow"
                api.post("/repos/${repo.value}/actions/workflows/tts-studio.yml/dispatches", JSONObject().apply {
                    put("ref", branch)
                    put("inputs", JSONObject().apply {
                        put("batch_id", compiled.batchId)
                        put("script_path", path)
                        put("shards", shards.toString())
                        put("strategy", strategy)
                        put("default_voice", script.defaultVoice)
                        put("default_speed", script.defaultSpeed.toString())
                        put("retention_days", retention.toString())
                        put("shard_indices", "")
                    })
                }.toString())

                var runId: Long? = null
                repeat(8) {
                    val page = JSONObject(api.get("/repos/${repo.value}/actions/runs?event=workflow_dispatch&per_page=30"))
                    val list = page.optJSONArray("workflow_runs") ?: JSONArray()
                    for (i in 0 until list.length()) {
                        val candidate = list.getJSONObject(i)
                        val message = candidate.optJSONObject("head_commit")?.optString("message") ?: ""
                        if (message.contains(compiled.batchId)) {
                            runId = candidate.getLong("id")
                            return@repeat
                        }
                    }
                    Thread.sleep(1200)
                }
                val run = Run(
                    batchId = compiled.batchId,
                    scriptId = script.id,
                    scriptTitle = script.title,
                    repo = repo.value,
                    runId = runId,
                    shards = shards,
                    strategy = strategy,
                    retentionDays = retention,
                    cleanup = cleanup,
                    compiledJson = gson.toJson(compiled.items),
                )
                withContext(Dispatchers.Main) { runs.add(0, run); persistRuns() }
            } catch (e: Exception) {
                withContext(Dispatchers.Main) { error.value = e.message ?: "Could not start generation" }
            } finally {
                withContext(Dispatchers.Main) { busy.value = false; status.value = null }
            }
        }
    }

    fun refreshRuns() {
        if (!connected.value) return
        viewModelScope.launch(Dispatchers.IO) {
            try {
                val api = client()
                var changed = false
                runs.filter { it.runId != null && !terminal(it.state) }.forEach { run ->
                    val detail = JSONObject(api.get("/repos/${run.repo}/actions/runs/${run.runId}"))
                    val jobs = JSONObject(api.get("/repos/${run.repo}/actions/runs/${run.runId}/jobs?per_page=100"))
                    val array = jobs.optJSONArray("jobs") ?: JSONArray()
                    var step = "Queued"
                    for (i in 0 until array.length()) {
                        val job = array.getJSONObject(i)
                        if (!job.optString("name").startsWith("synthesize")) continue
                        val steps = job.optJSONArray("steps") ?: JSONArray()
                        for (j in 0 until steps.length()) {
                            val s = steps.getJSONObject(j)
                            if (s.optString("status") == "in_progress") step = s.optString("name")
                        }
                    }
                    val state = if (detail.optString("status") != "completed") {
                        if (detail.optString("status") == "in_progress") "in_progress" else "queued"
                    } else when (detail.optString("conclusion")) {
                        "success" -> "success"
                        "failure" -> "failure"
                        "cancelled" -> "cancelled"
                        else -> "success"
                    }
                    if (run.state != state || run.step != step) {
                        run.state = state
                        run.step = step
                        if (state == "failure") run.error = "One or more shards failed."
                        changed = true
                    }
                }
                if (changed) withContext(Dispatchers.Main) { persistRuns() }
            } catch (_: Exception) {
                // polling is best effort
            }
        }
    }

    fun download(run: Run) {
        busy.value = true
        error.value = null
        status.value = "Downloading audio"
        viewModelScope.launch(Dispatchers.IO) {
            try {
                val api = client()
                val page = JSONObject(api.get("/repos/${run.repo}/actions/runs/${run.runId}/artifacts?per_page=100"))
                val list = page.optJSONArray("artifacts") ?: JSONArray()
                val items: MutableList<Item> = gson.fromJson(
                    run.compiledJson,
                    object : TypeToken<MutableList<Item>>() {}.type,
                ) ?: mutableListOf()
                val byName = items.associateBy { it.filename }
                val newAssets = mutableListOf<Asset>()
                for (i in 0 until list.length()) {
                    val artifact = list.getJSONObject(i)
                    val name = artifact.optString("name")
                    if (!name.startsWith("tts-${run.batchId}-shard-")) continue
                    val bytes = api.downloadBytes(artifact.getString("archive_download_url"))
                    files.unzipWavs(bytes, run.batchId).forEach { (filename, uri) ->
                        val base = filename.removeSuffix(".wav").removeSuffix(".WAV")
                        val item = byName[base] ?: return@forEach
                        newAssets.add(Asset(
                            batchId = run.batchId,
                            filename = filename,
                            text = item.text,
                            voice = item.voice,
                            speed = item.speed,
                            uri = uri,
                            index = items.indexOf(item),
                        ))
                    }
                }
                withContext(Dispatchers.Main) {
                    assets.addAll(newAssets)
                    persistAssets()
                    run.downloaded = true
                    persistRuns()
                }
                if (run.cleanup) cleanup(run)
            } catch (e: Exception) {
                withContext(Dispatchers.Main) { error.value = e.message ?: "Download failed" }
            } finally {
                withContext(Dispatchers.Main) { busy.value = false; status.value = null }
            }
        }
    }

    private fun cleanup(run: Run) {
        try {
            val api = client()
            api.delete("/repos/${run.repo}/actions/runs/${run.runId}")
            val branch = tokens.branch ?: "main"
            val path = "scripts/${run.batchId}.json"
            val sha = try {
                JSONObject(api.get("/repos/${run.repo}/contents/$path?ref=$branch")).optString("sha")
            } catch (_: GithubException) { null }
            if (sha != null) {
                api.put("/repos/${run.repo}/contents/$path", JSONObject().apply {
                    put("message", "chore: cleanup ${run.batchId}")
                    put("content", Base64.encodeToString("[]".toByteArray(), Base64.DEFAULT))
                    put("branch", branch)
                    put("sha", sha)
                }.toString())
            }
        } catch (_: Exception) { }
    }

    fun deleteRun(run: Run) {
        assets.filter { it.batchId == run.batchId }.forEach { files.delete(it.uri) }
        assets.removeAll { it.batchId == run.batchId }
        runs.removeAll { it.id == run.id }
        persistAssets(); persistRuns()
        if (run.cleanup) viewModelScope.launch(Dispatchers.IO) { cleanup(run) }
    }

    fun deleteAsset(asset: Asset) {
        files.delete(asset.uri)
        assets.removeAll { it.id == asset.id }
        persistAssets()
    }

    fun smartPaste(raw: String, script: Script) {
        val lines = raw.replace("\r\n", "\n").split(Regex("\\n\\s*\\n+"))
            .map { it.trim() }.filter { it.isNotEmpty() }
        lines.forEach { paragraph ->
            val speaker = Regex("^\\s*([A-Z][A-Za-z0-9 .'-]{0,28})\\s*:\\s*(.+)$").find(paragraph)
            val text = if (speaker != null) paragraph else paragraph
            script.blocks.add(Block(text = text, voice = script.defaultVoice, speed = script.defaultSpeed))
        }
        saveScript(script)
    }

    private fun terminal(state: String) = state in setOf("success", "failure", "cancelled", "timed_out", "skipped")
}
